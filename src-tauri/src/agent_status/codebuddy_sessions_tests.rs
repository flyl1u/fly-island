use super::*;
use crate::agent_status::snapshot::current_unix_millis;
use crate::agent_status::workbuddy_sessions::parse;
use serde_json::{json, Value};
use crate::agent_status::local_agent_files::scratch::tempdir;
use std::fs;

const SESSION: &str = "01a20787-8ed5-77cc-9b9f-cd12d3f37b32";

fn lines(records: &[Value]) -> String {
    records.iter().map(|record| format!("{record}\n")).collect()
}

fn user(text: &str, at: i64) -> Value {
    json!({ "type": "message", "role": "user", "sessionId": SESSION, "cwd": "D:/fly-island",
        "timestamp": at, "content": [{ "type": "input_text", "text": text }] })
}

fn assistant(text: &str, status: &str) -> Value {
    json!({ "type": "message", "role": "assistant", "status": status, "sessionId": SESSION,
        "content": [{ "type": "output_text", "text": text }],
        "providerData": { "requestModelName": "DeepSeek-V4.1-Flash",
            "rawUsage": { "total_tokens": 61137 } } })
}

fn call(id: &str) -> Value {
    json!({ "type": "function_call", "name": "Bash", "callId": id, "providerData": { "requestModelName": "DeepSeek-V4.1-Flash" }, "arguments": "{\"command\":\"ls -la\"}" })
}

fn result(id: &str) -> Value {
    json!({ "type": "function_call_result", "name": "Bash", "callId": id, "status": "completed" })
}

#[test]
fn phase_follows_the_turn_its_age_and_the_registry() {
    let now = 100 * 60 * 1000;
    let working = parse(&lines(&[user("hi", 1), call("a")]));
    let phase = |parsed: Parsed, updated_at: i64, closed: bool| {
        summary(parsed, "file", updated_at, now, closed).phase
    };
    assert_eq!(phase(working.clone(), now - 1_000, false), "running");
    assert_eq!(phase(working, now - AGENT_RUNNING_STALE_AFTER_MS, false), "stale");
    let done = parse(&lines(&[user("hi", 1), call("a"), result("a"), assistant("done", "completed")]));
    assert_eq!(phase(done, now - 1_000, false), "completed");
}

#[test]
fn the_row_names_codebuddy_and_its_terminal() {
    let now = 10_000;
    let working = parse(&lines(&[user("整理周报", 1_000), call("a")]));
    let row = summary(working, "file", now, now, false);
    assert_eq!((row.provider, row.phase, row.closed), ("codebuddy", "running", false));
    assert_eq!(row.host.map(|host| (host.name, host.kind)), Some(("CodeBuddy".to_string(), "terminal")));
    assert_eq!(row.title.as_deref(), Some("整理周报"));
    assert_eq!(row.current_tool.map(|tool| tool.name), Some("Bash".to_string()));
    assert_eq!(row.model.as_deref(), Some("DeepSeek-V4.1-Flash"));
    let ended = summary(row_parsed(), "file", now, now, true);
    assert_eq!((ended.phase, ended.closed, ended.current_tool), ("completed", true, None));
}

fn row_parsed() -> Parsed {
    parse(&lines(&[user("hi", 1), call("a")]))
}

#[test]
fn list_sessions_reads_recent_logs_and_the_open_registry() {
    let profile = tempdir();
    let home = profile.path();
    assert!(list_sessions(home, current_unix_millis(), 60 * 60 * 1000).is_empty());
    assert!(live_process_chain(home, SESSION).is_empty());
    let root = home.join(".codebuddy");
    let project = root.join("projects").join("demo");
    fs::create_dir_all(&project).expect("create the project folder");
    fs::create_dir_all(root.join("sessions")).expect("create the registry folder");
    fs::write(project.join(format!("{SESSION}.jsonl")), lines(&[user("整理周报", 1_000), call("a")]))
        .expect("write a log");
    fs::write(
        root.join("sessions").join(format!("{}.json", std::process::id())),
        json!({ "pid": std::process::id(), "sessionId": SESSION, "kind": "interactive" }).to_string(),
    )
    .expect("write a registry entry");

    let sessions = list_sessions(home, current_unix_millis(), 60 * 60 * 1000);
    let chain = live_process_chain(home, SESSION);

    assert_eq!(sessions.len(), 1);
    let row = &sessions[0];
    assert_eq!((row.provider, row.session_id.as_str()), ("codebuddy", SESSION));
    assert_eq!(row.phase, "running");
    assert!(!row.closed);
    assert!(!chain.is_empty(), "the registry pid leads to a running process");
}

#[test]
fn a_command_note_never_names_a_session() {
    let caveat = json!({ "type": "message", "role": "user", "sessionId": SESSION,
        "content": [{ "type": "input_text", "text": "Caveat: The messages below were generated by the user while running local commands." }] });
    let parsed = parse(&lines(&[caveat, user("整理周报", 1_000)]));
    assert_eq!(parsed.first_prompt.as_deref(), Some("整理周报"));
    let note = json!({ "type": "message", "role": "user",
        "content": [{ "type": "input_text", "text": "<local-command-stdout>change session x</local-command-stdout>" }] });
    assert_eq!(parse(&lines(&[note])).first_prompt, None);
    let wrapped = json!({ "type": "message", "role": "user", "content": [{ "type": "input_text",
        "text": "<system-reminder data-role=command-caveat>Caveat: The messages below were generated.</system-reminder>" }] });
    assert_eq!(parse(&lines(&[wrapped])).first_prompt, None);
}

#[test]
fn a_tool_call_alone_still_names_the_model_and_context() {
    let tool = json!({ "type": "function_call", "name": "Bash", "callId": "a",
        "providerData": { "requestModelName": "Glm-5.3" },
        "message": { "usage": { "total_tokens": 15240 } } });
    let parsed = parse(&lines(&[user("hi", 1), tool]));
    assert_eq!(parsed.model.as_deref(), Some("Glm-5.3"));
    assert_eq!(parsed.context_tokens, Some(15240));
}

#[test]
fn the_scan_is_throttled_to_once_per_two_seconds() {
    use std::sync::{atomic::{AtomicUsize, Ordering}, Mutex};
    static SLOT: crate::agent_status::NativeSessions = Mutex::new(None);
    let reads = AtomicUsize::new(0);
    let read = || {
        reads.fetch_add(1, Ordering::Relaxed);
        Vec::new()
    };
    for _ in 0..5 {
        crate::agent_status::throttled(&SLOT, 1_000, read);
    }
    assert_eq!(reads.load(Ordering::Relaxed), 1);
    crate::agent_status::throttled(&SLOT, 2_000, read);
    assert_eq!(reads.load(Ordering::Relaxed), 2, "a different window reads again");
}
