pub(crate) fn name(product_id: u16) -> Option<&'static str> {
    MODELS
        .iter()
        .find(|(id, _)| *id == product_id)
        .map(|(_, name)| *name)
}

pub(crate) fn is_known_receiver(product_id: u16) -> bool {
    name(product_id).is_some()
}
