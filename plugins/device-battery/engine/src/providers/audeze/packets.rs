//! HeadsetControl's request tables for the Maxwell, byte for byte
//! (Sapd/HeadsetControl, lib/devices/audeze_maxwell.hpp). Each request is padded to
//! the 62-byte output report 06.

pub(super) const MESSAGE_BYTES: usize = 62;

pub(super) fn packet(values: &[u8]) -> [u8; MESSAGE_BYTES] {
    let mut data = [0; MESSAGE_BYTES];
    data[..values.len()].copy_from_slice(values);
    data
}

